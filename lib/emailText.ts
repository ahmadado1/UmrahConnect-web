/**
 * Agency email text in the 6 website languages.
 * The agency's language is saved in agents.language when they sign up or switch language on the website.
 * Placeholders: {name}, {business}, {code}.
 */

export type EmailLang = "en" | "ar" | "fr" | "tr" | "ur" | "bn"

const LANGS: EmailLang[] = ["en", "ar", "fr", "tr", "ur", "bn"]

/** Any saved value ("fr", "FR", "fr-FR", null…) → one of our 6 languages, English if unknown. */
export function emailLang(value: string | null | undefined): EmailLang {
  const code = String(value || "").trim().toLowerCase().slice(0, 2) as EmailLang
  return LANGS.includes(code) ? code : "en"
}

/** Arabic and Urdu read right to left. */
export function isRtlLang(lang: EmailLang) {
  return lang === "ar" || lang === "ur"
}

